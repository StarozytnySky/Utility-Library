package org.broken.arrow.library.database.config;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.Locale;
import java.util.Objects;

import org.bukkit.configuration.InvalidConfigurationException;
import org.bukkit.configuration.file.YamlConfiguration;
import org.bukkit.plugin.Plugin;

/**
 * Reads plugin-local database settings without exposing provider-specific setup to consumers.
 *
 * <p>Configuration is loaded once during bootstrap. A missing file is copied from the
 * plugin's own resources, or from the database module's bundled template. Existing
 * files are never overwritten. The configuration reader does not open a connection.</p>
 */
public final class DatabaseConfigurationLoader {
    private static final String DEFAULT_RESOURCE = "database.yml";

    private DatabaseConfigurationLoader() { }

    /**
     * Loads or creates {@code database.yml} inside the given plugin's data directory.
     *
     * @param plugin owning plugin
     * @return validated, immutable configuration
     */
    public static DatabaseConfiguration load(Plugin plugin) {
        Objects.requireNonNull(plugin, "plugin");
        Path folder = plugin.getDataFolder().toPath().toAbsolutePath().normalize();
        Path file = folder.resolve(DEFAULT_RESOURCE);
        try {
            Files.createDirectories(folder);
            if (Files.notExists(file)) {
                try (InputStream source = openDefaultResource(plugin)) {
                    if (source == null) {
                        throw new IllegalStateException("Missing database.yml resource template");
                    }
                    // Avoid overwriting a file concurrently generated by another bootstrap.
                    try {
                        Files.copy(source, file);
                    } catch (java.nio.file.FileAlreadyExistsException ignored) {
                        // The existing file takes precedence.
                    }
                }
            }
        } catch (IOException failure) {
            throw new IllegalStateException("Could not prepare plugin database.yml", failure);
        }
        return load(file, folder);
    }

    /**
     * Loads configuration from a specified YAML file. Relative SQLite files remain
     * confined to {@code dataDirectory} to prevent accidental writes elsewhere.
     *
     * @param file existing YAML file
     * @param dataDirectory root directory for local database files
     * @return validated configuration
     */
    public static DatabaseConfiguration load(Path file, Path dataDirectory) {
        Objects.requireNonNull(file, "file");
        Objects.requireNonNull(dataDirectory, "dataDirectory");
        YamlConfiguration yaml = new YamlConfiguration();
        try {
            yaml.load(file.toFile());
        } catch (IOException | InvalidConfigurationException failure) {
            throw new IllegalArgumentException("Invalid database.yml: cannot read configuration", failure);
        }
        String rawKind = required(yaml, "database.type");
        DatabaseKind kind;
        try {
            kind = DatabaseKind.valueOf(rawKind.toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException failure) {
            throw new IllegalArgumentException("Unsupported database.type: " + rawKind, failure);
        }

        String address = kind == DatabaseKind.SQLITE
                ? sqliteAddress(dataDirectory, required(yaml, "database.sqlite-file"))
                : required(yaml, "database.url");

        DatabaseConfiguration.Builder builder = DatabaseConfiguration.forKind(kind, address)
                .poolSize(number(yaml, "database.pool-size", kind == DatabaseKind.SQLITE ? 1 : 10))
                .workers(number(yaml, "database.workers", 2),
                        number(yaml, "database.queue-capacity", 2_048))
                .connectionTimeout(Duration.ofMillis(number(yaml, "database.connection-timeout-ms", 10_000)))
                .shutdownTimeout(Duration.ofMillis(number(yaml, "database.shutdown-timeout-ms", 15_000)))
                .sqliteOptions(yaml.getBoolean("database.sqlite-wal", true),
                        number(yaml, "database.sqlite-busy-timeout-ms", 5_000))
                .sqliteSynchronousMode(SqliteSynchronousMode.parse(
                        yaml.getString("database.sqlite-synchronous-mode", "FULL")));
        if (kind == DatabaseKind.MONGODB) {
            builder.database(required(yaml, "database.name"));
        }
        String username = yaml.getString("database.username", "");
        String password = yaml.getString("database.password", "");
        if (!username.isBlank() || !password.isEmpty()) {
            if (username.isBlank()) {
                throw new IllegalArgumentException("database.username is required when a password is supplied");
            }
            builder.credentials(username, password);
        }
        return builder.build();
    }

    private static InputStream openDefaultResource(Plugin plugin) {
        InputStream source = plugin.getResource(DEFAULT_RESOURCE);
        return source != null ? source : DatabaseConfigurationLoader.class.getResourceAsStream("/database-default.yml");
    }

    private static String required(YamlConfiguration yaml, String key) {
        String value = yaml.getString(key);
        if (value == null || value.isBlank()) {
            throw new IllegalArgumentException("Missing required database configuration: " + key);
        }
        return value.trim();
    }

    private static int number(YamlConfiguration yaml, String key, int fallback) {
        if (!yaml.contains(key)) return fallback;
        if (!yaml.isInt(key)) {
            throw new IllegalArgumentException("Database configuration must be an integer: " + key);
        }
        return yaml.getInt(key);
    }

    private static String sqliteAddress(Path dataDirectory, String fileName) {
        Path root = dataDirectory.toAbsolutePath().normalize();
        Path relative = Path.of(fileName);
        if (relative.isAbsolute()) {
            throw new IllegalArgumentException("database.sqlite-file must be relative to plugin data folder");
        }
        Path resolved = root.resolve(relative).normalize();
        if (!resolved.startsWith(root) || resolved.equals(root)) {
            throw new IllegalArgumentException("database.sqlite-file escapes plugin data folder");
        }
        try {
            Path parent = resolved.getParent();
            Files.createDirectories(parent);
            Path actualRoot = root.toRealPath();
            if (!parent.toRealPath().startsWith(actualRoot)
                    || (Files.exists(resolved) && !resolved.toRealPath().startsWith(actualRoot))) {
                throw new IllegalArgumentException("database.sqlite-file resolves outside plugin data folder");
            }
        } catch (IOException failure) {
            throw new IllegalStateException("Could not prepare SQLite data directory", failure);
        }
        return "jdbc:sqlite:" + resolved;
    }
}
